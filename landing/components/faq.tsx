export function Faq() {
  const [open, setOpen] = useState<number | null>(0);

  return (
    <div className="divide-y divide-ink-line border-y border-ink-line">
      {ITEMS.map((item, index) => {
        const isOpen = open === index;
        return (
          <div key={item.q}>
            <button
              type="button"
              onClick={() => setOpen(isOpen ? null : index)}
              aria-expanded={isOpen}
              className="flex w-full items-start justify-between gap-6 py-5 text-left"
            >
              <span
                className={`text-lg font-medium transition-colors ${
                  isOpen ? "text-cyan-accent" : "text-white"
                }`}
              >
                {item.q}
              </span>
              <span
                aria-hidden
                className={`mt-1 shrink-0 text-xl leading-none transition-transform ${
                  isOpen ? "rotate-45 text-cyan-accent" : "text-white/40"
                }`}
              >
                +
              </span>
            </button>
            {isOpen && (
              <p className="max-w-3xl pb-6 text-white/60 rise">{item.a}</p>
            )}
          </div>
        );
      })}
    </div>
  );
}
